#!/usr/bin/env python3
"""Cost and weight summary from bom/bom.yaml + the STL volumes -> docs/BOM.md"""
import os, sys, yaml
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
b = yaml.safe_load(open(os.path.join(ROOT, 'bom', 'bom.yaml'), encoding='utf-8'))
try:
    import trimesh
except ImportError:
    trimesh = None
RHO, FILL = 1.27, 0.62          # PETG g/cm3; effective solid fraction at 4 walls + 40 % infill on parts this size
out = ['# Bill of materials and cost (generated by scripts/bom.py)\n',
       'Prices are typical online prices in EUR (2026) and only indicative. Masses are estimates.\n',
       '## Purchased parts\n', '| Group | Item | Qty | Unit € | Total € |', '|---|---|---|---|---|']
tot_eur = tot_g = 0.0
groups = {}
for it in b['items']:
    t = it['qty'] * it['eur']; tot_eur += t; tot_g += it['qty'] * it['mass_g']
    groups[it['group']] = groups.get(it['group'], 0) + t
    out.append(f"| {it['group']} | {it['item']} | {it['qty']} | {it['eur']:.2f} | {t:.2f} |")
print_g = 0.0
rows = []
for name, q in b['printed'].items():
    f = os.path.join(ROOT, 'stl', name + '.stl')
    g = None
    if trimesh and os.path.exists(f):
        m = trimesh.load(f)
        full = name.endswith(('act_disc', 'act_cam'))
        g = m.volume / 1000 * RHO * (1.0 if full else FILL)
        print_g += g * q
    rows.append((name, q, g))
fil = print_g / 1000 * b['filament_eur_per_kg'] * 1.15        # + 15 % waste/supports
tot_eur += fil; tot_g += print_g
out.append(f'| Printed | Filament PETG/ASA ({print_g / 1000:.2f} kg + 15 % waste) | 1 | | {fil:.2f} |')
out.append(f'| | **Total (one rotator, without battery and tripod)** | | | **{tot_eur:.0f} €** |\n')
out.append('By group: ' + ', '.join(f'{k} {v:.0f} €' for k, v in groups.items()) + f', printed parts {fil:.0f} €.\n')
out.append('## Printed parts\n\n| STL | Qty | Est. mass each (g) |\n|---|---|---|')
for n, q, g in rows:
    out.append(f"| `stl/{n}.stl` | {q} | {'' if g is None else f'{g:.0f}'} |")
out.append(f'\n## Weight estimate\n\nPrinted parts {print_g:.0f} g + purchased parts {tot_g - print_g:.0f} g = **{tot_g / 1000:.2f} kg** '
           '(rotator + e-box, without antenna, battery and tripod).\n')
out.append('## Optional\n\n| Item | € |\n|---|---|')
for o in b['optional']:
    out.append(f"| {o['item']} | {o['eur']} |")
open(os.path.join(ROOT, 'docs', 'BOM.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print(f'total {tot_eur:.0f} EUR, {tot_g / 1000:.2f} kg (printed {print_g:.0f} g)')


def lsr2():
    """LSR-2 BOM: bom/bom_lsr2.yaml (route/material/files/price) + masses read from build/lsr2_build_report.json -> docs/BOM_LSR2.md.

    Masses are never typed in the yaml; the total is checked within 1 % against an independent sum (reported volume x density)."""
    import json
    sys.path.insert(0, os.path.join(ROOT, 'cad', 'lsr2'))
    sys.path.insert(0, os.path.join(ROOT, 'calc'))
    import params as P
    import axes as AX
    import parts_table as PT
    import lsr2_materials as M
    c = yaml.safe_load(open(os.path.join(ROOT, 'bom', 'bom_lsr2.yaml'), encoding='utf-8'))
    rep = json.load(open(os.path.join(ROOT, 'build', 'lsr2_build_report.json')))
    fab = c['fabricated']
    t = M.totals(rep)
    expected = set(rep['parts']) | {f'shafts.{n}' for n in rep['shafts']}
    listed = {f['report']: f for f in fab}
    if set(listed) != expected:
        sys.exit(f'LSR-2 BOM parts differ from the build report: {sorted(set(listed) ^ expected)}')
    rows, fab_g, eur_fab, indep_g = [], 0.0, 0.0, 0.0
    for k, f in listed.items():
        if k.startswith('shafts.'):
            s = next(x for x in t['shafts'] if x['name'] == k.split('.')[1])
            rows.append(f"| {PT.pos_for(k)} | `{f['part']}` | turned | {f['material']} | 1 | {s['fin_g']:.1f} | {s['cost']:.1f} | | | {s['cost']:.1f} | {f['source']} | {f.get('alt', '')} |")
            fab_g += s['fin_g']
            eur_fab += s['cost']
            indep_g += rep['shafts'][k.split('.')[1]]['volume_cm3'] * AX.SS_G_CM3
            continue
        cmp_, v = t['cmp'][k], rep['parts'][k]
        d = cmp_['default']
        x = cmp_[d]
        rows.append(f"| {PT.pos_for(k)} | `{f['part']}` | **{d}** ({'cast' if d == 'A' else 'CNC'}) | {f['material_' + d.lower()]} | {cmp_['qty']} | {x['fin_g']:.1f} | "
                    f"{cmp_['A']['eur'] / cmp_['qty']:.1f} | {cmp_['B']['eur'] / cmp_['qty']:.1f} | {x['eur'] / cmp_['qty']:.1f} | {x['eur'] - x['pla_eur']:.1f} | "
                    f"{f['source_' + d.lower()]} | {f.get('alt', '')} |")
        fab_g += cmp_['qty'] * x['fin_g']
        eur_fab += x['eur'] - x['pla_eur']
        indep_g += cmp_['qty'] * (v['finished_cm3'] * P.ALU_CAST_G_CM3 if d == 'A' else v['route_b']['finished_cm3'] * P.CNC['density'])
    tube = next(i for i in c['items'] if i['group'] == 'Cross boom')
    tube['mass_g'] = rep['items']['cross_boom']['mass_g'] / tube['qty']
    for it in c['items']:                       # masses of the lift arm and the counterweight come from the build report
        if it.get('ref') in ('lift_arm', 'counterweight'):
            it['mass_g'] = rep['items'][it['ref']]['mass_g']
    refs = {it['ref'] for it in c['items'] if it.get('ref')} | set(listed)
    if {p['ref'] for p in PT.PARTS if p['ref']} - refs:
        sys.exit(f"parts_table balloons without a BOM entry: {sorted({p['ref'] for p in PT.PARTS if p['ref']} - refs)}")
    if abs(fab_g - indep_g) > 0.01 * indep_g:
        sys.exit(f'LSR-2 BOM fabricated mass {fab_g:.0f} g vs volume x density {indep_g:.0f} g (> 1 %)')
    rep_g = fab_g
    o = ['# LSR-2 bill of materials and cost (generated by scripts/bom.py)\n',
         'Source: `bom/bom_lsr2.yaml`. Authors: Anatol EA5KAO, Diego EA5JEF, Pedro Roca Molina (BricoHams). '
         'Every price and every bought-part mass is **VERIFY** (generic values, local quotes). Fabricated masses are read from '
         '`build/lsr2_build_report.json` (finished solids); costs of both routes come from `calc/lsr2_materials.py`; the script checks the fabricated total within 1 % against reported volume x density. '
         'Goal: light and cheap: the default route of each part is the cheaper one (within 5 % the lighter).\n',
         '## Fabricated parts (route A sand cast + machining, route B 3-axis CNC from block, turned shafts)\n',
         '| Pos | Part | Default route | Material | Qty | Finished mass (g each) | Route A € each | Route B € each | Default € each | Default € total (without PLA) | Source files | Note |',
         '|---|---|---|---|---|---|---|---|---|---|---|---|'] + rows
    o.append(f'| | **Fabricated total** | | | | **{fab_g:.0f}** | | | | **{eur_fab:.0f}** | | |')
    o.append('\nRoute A cost = poured A356 + foundry + machining of the stock pads; route B = block stock + machining minutes (PARAMETRIC rates, LSR2_MATERIALS). '
             'Shafts cost bar only (turning not included). The pattern PLA is listed under the totals.\n')
    o += ['## Bought parts, fasteners and electronics\n',
          '| Pos | Group | Item | Qty | Unit € (VERIFY) | Total € | Cheaper |', '|---|---|---|---|---|---|---|']
    eur_b = g_b = 0.0
    groups = {}
    for it in c['items']:
        line = it['qty'] * it['eur']
        eur_b += line
        g_b += it['qty'] * it['mass_g']
        groups[it['group']] = groups.get(it['group'], 0) + line
        o.append(f"| {PT.pos_for(it.get('ref'))} | {it['group']} | {it['item']} | {it['qty']} | {it['eur']:.2f} | {line:.2f} | {it.get('alt', '')} |")
    tot_eur = eur_fab + eur_b + t['pla_eur']
    tot_g = fab_g + g_b
    o += [f'| | **Bought total** | | | | **{eur_b:.0f}** | |\n',
          '## Totals (VERIFY)\n', '| Item | Value |', '|---|---|',
          f'| Fabricated parts (default routes) | {eur_fab:.0f} € / {fab_g / 1000:.2f} kg |',
          f'| Bought parts, fasteners, electronics | {eur_b:.0f} € / {g_b / 1000:.2f} kg (estimated masses) |',
          f"| PLA patterns and cores of the cast parts | {t['pla_eur']:.0f} € ({t['pla_kg']:.2f} kg PLA, not in the mass) |",
          f'| **Total, one rotator without mast, antenna and cable run** | **{tot_eur:.0f} €** |',
          f'| **Mass, rotator and electronics** | **{tot_g / 1000:.2f} kg** |',
          '\nBy group: ' + ', '.join(f'{k} {v:.0f} €' for k, v in groups.items()) + f', fabricated {eur_fab:.0f} €, PLA {t["pla_eur"]:.0f} €.\n',
          'The two NMRV030 gearboxes and the two NEMA23 motors dominate the mass and the cost of the bought parts; see [LSR2_MATERIALS](LSR2_MATERIALS.md) for the cost model and [LSR2_ASSEMBLY](LSR2_ASSEMBLY.md) for the build.']
    if c.get('budget'):   # separate variant: not in the totals above
        o += ['\n## Budget build variant (not the default, not in the totals above)\n', c['budget_note'], '',
              '| Item | Qty | Unit € (VERIFY) | Total € | Replaces / consequence |', '|---|---|---|---|---|']
        o += [f"| {b['item']} | {b['qty']} | {b['eur']:.2f} | {b['qty'] * b['eur']:.2f} | {b['replaces']} |" for b in c['budget']]
    open(os.path.join(ROOT, 'docs', 'BOM_LSR2.md'), 'w', encoding='utf-8', newline='\n').write('\n'.join(o) + '\n')
    print(f'LSR-2 total {tot_eur:.0f} EUR, {tot_g / 1000:.2f} kg (fabricated {fab_g:.0f} g, report {rep_g:.0f} g)')


lsr2()
