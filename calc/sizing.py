#!/usr/bin/env python3
"""LSR-1 engineering budget: torque, speed, pass dynamics and energy.

Writes docs/SIZING.md and docs/img/{torque,passes,energy}.png. Every input is at the top:
change it for your antenna/motor and re-run (`make calc`).
"""
import math, os, sys
from datetime import datetime, timezone

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'software')); sys.path.insert(0, os.path.join(ROOT, 'software', 'tests'))
IMG = os.path.join(ROOT, 'docs', 'img'); os.makedirs(IMG, exist_ok=True)
INK, GRID, BG = '#52514e', '#e4e3df', '#fcfcfb'
C1, C2, C3 = '#2a78d6', '#eb6834', '#1baf7a'
plt.rcParams.update({'axes.edgecolor': INK, 'axes.labelcolor': INK, 'xtick.color': INK, 'ytick.color': INK,
                     'text.color': INK, 'axes.grid': True, 'grid.color': GRID, 'figure.facecolor': BG, 'axes.facecolor': BG,
                     'font.size': 10, 'axes.spines.top': False, 'axes.spines.right': False})

# ------------------------------------------------------------------ inputs
ANT_MASS = 1.0          # kg  SpaceQuad / Arrow-class dual-band antenna incl. clamp (weigh yours)
ANT_AREA = 0.10         # m^2 projected wind area (elements + boom), worst orientation
CP_OFFSET = 0.15        # m   centre of pressure vs EL axis when clamped at the CG (asymmetric elements)
CG_ERROR = 0.02         # m   residual imbalance after balancing
STUB_ARM = 0.20         # m   antenna clamp distance from the EL actuator face (cantilever)
WIND_OP = 10.0          # m/s operating wind (Beaufort 5)
WIND_SURV = 20.0        # m/s survival (powered, holding)
RHO, CD = 1.225, 1.2
RATIO, EFF = 25.0, 0.75 # printed cycloid; efficiency measured on similar printed drives 0.7-0.85
MOTORS = {              # holding torque (Nm) at rated current (A); torque ~ proportional to current
    '17HS4401 (40 mm, 1.7 A)': (0.42, 1.7, 1.5),        # (T_hold, I_rated, R_phase)
    '17HS08-1004S pancake (20 mm, 1.0 A)': (0.13, 1.0, 3.5),
}
I_RUN = 0.9             # A rms (firmware irun default)
I_HOLD_PCT = 0.35
VMAX = 20.0             # deg/s output
# electronics (W)
P_PI, P_PICO, P_GPS, P_DRV = 1.2, 0.15, 0.15, 0.25
BUCK_EFF = 0.88


def wind_force(v):
    return 0.5 * RHO * v * v * CD * ANT_AREA


def motor_torque_out(name, i_rms, rpm):
    t_hold, i_rated, _ = MOTORS[name]
    t0 = t_hold * min(1.0, i_rms / i_rated)          # low-speed torque at the set current
    t = t0 * 0.75 / (1.0 + rpm / 350.0)              # 16 usteps, 12 V: pull-out falls with speed (typical 17HS curve)
    return t * RATIO * EFF


def main():
    out = []
    g = 9.81
    t_el_imb = ANT_MASS * g * CG_ERROR
    t_el_wind = wind_force(WIND_OP) * CP_OFFSET
    t_el = t_el_imb + t_el_wind
    t_az_wind = wind_force(WIND_OP) * CP_OFFSET          # same asymmetry about the vertical axis
    m_stub = ANT_MASS * g * STUB_ARM                      # bending on the EL output bearings
    out.append('# Engineering budget (generated by calc/sizing.py)\n')
    out.append(f'Inputs: antenna {ANT_MASS} kg, wind area {ANT_AREA} m², centre-of-pressure offset {CP_OFFSET} m, '
               f'residual imbalance {CG_ERROR * 1000:.0f} mm, operating wind {WIND_OP} m/s, gearbox {RATIO:.0f}:1 at {EFF:.0%}.\n')
    out.append('## Load torque\n')
    out.append('| Load | EL (Nm) | AZ (Nm) |\n|---|---|---|')
    out.append(f'| Residual imbalance | {t_el_imb:.2f} | 0 |')
    out.append(f'| Wind {WIND_OP:.0f} m/s ({wind_force(WIND_OP):.1f} N) | {t_el_wind:.2f} | {t_az_wind:.2f} |')
    out.append(f'| **Total, operating** | **{t_el:.2f}** | **{t_az_wind:.2f}** |')
    out.append(f'| Wind {WIND_SURV:.0f} m/s (holding) | {wind_force(WIND_SURV) * CP_OFFSET + t_el_imb:.2f} | {wind_force(WIND_SURV) * CP_OFFSET:.2f} |\n')
    out.append(f'Cantilever moment on the EL output bearings: {m_stub:.1f} Nm static (2 × 61810, C0 ≈ 6 kN each: large margin).\n')

    out.append('## Available torque at the output\n')
    out.append('| Motor | Current | Holding (powered, standstill) | Running at 2°/s | Running at 20°/s | Safety factor EL @ 2°/s |\n|---|---|---|---|---|---|')
    for name in MOTORS:
        rpm = lambda dps: dps / 6.0 * RATIO
        for i in (I_RUN, 1.2):
            hold = MOTORS[name][0] * min(1, i / MOTORS[name][1]) * RATIO * EFF
            t2, t20 = motor_torque_out(name, i, rpm(2)), motor_torque_out(name, i, rpm(20))
            out.append(f'| {name} | {i:.1f} A | {hold:.1f} Nm | {t2:.1f} Nm | {t20:.1f} Nm | {t2 / t_el:.1f} |')
    out.append('\nThe 40 mm motor at 0.9 A gives a safety factor above 2 for a SpaceQuad-class antenna in 10 m/s wind. '
               'The pancake "Lite" motor is only for antennas under ~0.6 kg in light wind.\n')
    # torque plot
    fig, ax = plt.subplots(figsize=(7, 3.8))
    dps = [x / 10 for x in range(1, 301)]
    for (name, col) in zip(MOTORS, (C1, C3)):
        ax.plot(dps, [motor_torque_out(name, I_RUN, d / 6 * RATIO) for d in dps], color=col, lw=2, label=f'{name.split(" (")[0]} @ {I_RUN} A')
    ax.axhline(t_el, color=C2, lw=2, ls='--', label=f'EL load, {WIND_OP:.0f} m/s wind')
    ax.axvspan(0, 4, color=GRID, alpha=0.6, label='LEO tracking (normal + flip plans)')
    ax.set_xlabel('output speed (deg/s)'); ax.set_ylabel('output torque (Nm)'); ax.set_ylim(0, None); ax.set_xlim(0, 30)
    ax.legend(frameon=False, fontsize=8); fig.tight_layout(); fig.savefig(os.path.join(IMG, 'torque.png'), dpi=150); plt.close(fig)
    out.append('![Torque](img/torque.png)\n')

    # ---- pass dynamics with the real planner
    from conftest import TLES
    from lsr.astro import load_tle_text, Observer
    from lsr.passes import find_passes, plan_pass, Limits
    obs = Observer(40.4168, -3.7038, 650)
    sats = load_tle_text(TLES)
    t0 = datetime(2026, 10, 1, tzinfo=timezone.utc)
    lim = Limits(0, 450, 0, 180, VMAX, 15)
    rows = []
    for n in ('ISS (ZARYA)', 'SO-50', 'AO-91', 'RS-44'):
        for p in find_passes(sats[n], obs, t0, 24 * 7, 0, 5):
            a = plan_pass(p, lim, 0.0, allow_flip=False)
            b = plan_pass(p, lim, 0.0, allow_flip=True)
            rows.append((p.max_el, a.peak_az_rate if a and a.feasible else float('nan'), b.peak_az_rate, b.mode, b.max_error))
    fig, ax = plt.subplots(figsize=(7, 3.8))
    ax.scatter([r[0] for r in rows], [r[1] for r in rows], s=14, color=C2, label='az only (el 0-90), feasible wrap')
    ax.scatter([r[0] for r in rows], [r[2] for r in rows], s=14, color=C1, label='LSR planner (wrap 0-450 + flip)')
    ax.axhline(0.8 * VMAX, color=INK, lw=1, ls=':', label='80 % of vmax_az')
    ax.set_yscale('log'); ax.set_xlabel('pass maximum elevation (deg)'); ax.set_ylabel('peak azimuth rate (deg/s)')
    ax.legend(frameon=False, fontsize=8); fig.tight_layout(); fig.savefig(os.path.join(IMG, 'passes.png'), dpi=150); plt.close(fig)
    nflip = sum(1 for r in rows if r[3] != 'normal'); worst = max(r[4] for r in rows)
    over = sum(1 for r in rows if not (r[1] <= 0.8 * VMAX))
    out.append('## Pass dynamics (one week, 4 satellites, Madrid)\n')
    out.append(f'{len(rows)} passes above 5°. Without flip and with a plain 0-360 rotator, {over} of them either exceed '
               f'{0.8 * VMAX:.0f}°/s in azimuth or hit the cable-wrap limit mid-pass. The planner used {nflip} flip/over-the-top '
               f'trajectories; all passes stay below {0.8 * VMAX:.0f}°/s with a worst pointing error of {worst:.2f}°.\n')
    out.append('![Passes](img/passes.png)\n')

    # ---- energy
    r = MOTORS['17HS4401 (40 mm, 1.7 A)'][2]
    p_run = 2 * (2 * I_RUN ** 2 * r) + 2 * P_DRV
    p_hold = 2 * (2 * (I_RUN * I_HOLD_PCT) ** 2 * r) + 2 * P_DRV
    p_el = (P_PI + P_PICO + P_GPS) / BUCK_EFF
    p_track, p_idle = p_run + p_el, p_hold + p_el
    duty = 0.3
    p_avg = duty * p_track + (1 - duty) * p_idle
    packs = [('LiFePO4 12.8 V 6 Ah', 76.8 * 0.9), ('LiFePO4 12.8 V 12 Ah', 153.6 * 0.9),
             ('USB-C PD power bank 20 000 mAh (12 V PD trigger)', 74 * 0.85), ('USB-C PD power bank 26 800 mAh', 99 * 0.85),
             ('3S Li-ion 18650 pack 3.5 Ah (11.1 V)', 38.9 * 0.9)]
    out.append('## Energy budget\n')
    out.append('| State | Power at 12 V |\n|---|---|')
    out.append(f'| Tracking (both motors at run current {I_RUN} A) | {p_track:.1f} W |')
    out.append(f'| Idle between passes (hold {I_HOLD_PCT:.0%}) | {p_idle:.1f} W |')
    out.append(f'| Pi Zero 2 W + Pico + GPS (through the buck) | {p_el:.1f} W |')
    out.append(f'| **Average, {duty:.0%} of the time tracking** | **{p_avg:.1f} W** |\n')
    out.append('| Battery | Usable energy | Hours of operation |\n|---|---|---|')
    for n, e in packs:
        out.append(f'| {n} | {e:.0f} Wh | {e / p_avg:.1f} h |')
    fig, ax = plt.subplots(figsize=(7, 3.2))
    names = [n.split(' (')[0] for n, _ in packs]
    ax.barh(names, [e / p_avg for _, e in packs], color=[C1, C1, C3, C3, C2])
    ax.set_xlabel(f'hours at {p_avg:.1f} W average'); ax.invert_yaxis(); fig.tight_layout()
    fig.savefig(os.path.join(IMG, 'energy.png'), dpi=150); plt.close(fig)
    out.append('\n![Energy](img/energy.png)\n')
    open(os.path.join(ROOT, 'docs', 'SIZING.md'), 'w').write('\n'.join(out) + '\n')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
